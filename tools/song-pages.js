#!/usr/bin/env node
/*
 * Calm Match — one public page per sing-along song, for families and teachers searching
 * for a song's words in Irish ("Twinkle Twinkle Little Star in Irish").
 *
 *   node tools/song-pages.js            Write the pages for the songs listed in
 *                                       tools/song-pages.json, remove pages for songs no
 *                                       longer listed, and update the sitemap and the
 *                                       "Words in Irish and English" list on Sing along.
 *   node tools/song-pages.js --check    Change nothing; exit 1 if the pages, sitemap or list
 *                                       are out of date (check.py runs this).
 *   node tools/song-pages.js --preview <id> --site <copy of site/>
 *                                       Also write <id>'s page, even if not listed, into a
 *                                       copy of the site, to look at before it is approved.
 *
 * A song is listed (published) only once the Irish checker has approved its Irish words.
 * Pages are plain HTML: no scripts, no outside files, the site's own stylesheet.
 * Uses the same lyric parsing as the site (site/singalong/shared.js).
 */
'use strict';
var fs = require('fs');
var path = require('path');
var vm = require('vm');

var args = process.argv.slice(2);
function opt(name) { var i = args.indexOf(name); return i > -1 ? args[i + 1] : null; }
var CHECK = args.indexOf('--check') > -1;
var PREVIEW = opt('--preview');
var SITE = path.resolve(opt('--site') || path.join(__dirname, '..', 'site'));
var DIR = path.join(SITE, 'singalong');
var BASE = 'https://calmmatch.com/';
var MARK = '<!-- generated by tools/song-pages.js: edit songs.js or the tool, not this file -->';

// ---- load the songs with the site's own parser ----
var sandbox = { window: {}, console: { warn: function () {} } };
sandbox.window.console = sandbox.console;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(DIR, 'songs.js'), 'utf8'), sandbox);
vm.runInContext('var location = { search: "" }; var URLSearchParams = function () { return { get: function () { return null; } }; };', sandbox);
vm.runInContext(fs.readFileSync(path.join(DIR, 'shared.js'), 'utf8'), sandbox);
var SA = sandbox.window.SA;
var songs = sandbox.window.CALM_SONGS;
var byId = {};
songs.forEach(function (s) { byId[s.id] = s; });

var cfg = JSON.parse(fs.readFileSync(path.join(__dirname, 'song-pages.json'), 'utf8'));
var listed = (cfg.published || []).map(function (p) { return typeof p === 'string' ? { id: p } : p; });
var problems = [];
listed.forEach(function (p) {
  if (!byId[p.id]) problems.push('tools/song-pages.json lists "' + p.id + '", which is not in songs.js');
  else if (SA.build(byId[p.id]).problems.length) problems.push(p.id + ': ' + SA.build(byId[p.id]).problems.join('; '));
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
var published = listed.slice();
if (PREVIEW && !published.some(function (p) { return p.id === PREVIEW; })) {
  if (!byId[PREVIEW]) { console.error('No song "' + PREVIEW + '"'); process.exit(1); }
  published.push({ id: PREVIEW, preview: true });
}
// Page order follows songs.js, so the list on Sing along matches the picker.
var order = songs.map(function (s) { return s.id; });
published.sort(function (a, b) { return order.indexOf(a.id) - order.indexOf(b.id); });

function esc(s) {
  return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
  });
}

// Verses as arrays of display lines ("Twin|kle" → "Twinkle", "_" holds dropped).
function verses(song, lang) {
  var lines = song.lyrics[lang], p = SA.parse(lines), n = song.notes.length;
  var count = Math.max(1, Math.round(p.syl.length / n)), starts = [];
  for (var v = 0; v < count; v++) starts.push(v === 0 ? 0 : p.syl[v * n].line);
  starts.push(lines.length);
  var out = [];
  for (var i = 0; i < count; i++) {
    var group = [];
    for (var li = starts[i]; li < starts[i + 1]; li++) group.push(p.lines[li].map(function (w) { return w.text; }).join(' '));
    if (group.length) out.push(group);
  }
  return out;
}

function titles(song) {
  var en = song.title.en, ga = song.title.ga;
  var title = en + ' in Irish' + (ga && ga !== en ? ' (' + ga + ')' : '');
  var desc = 'Sing ' + en + ' in Irish and English: the words side by side, with a gentle tune to sing along to. Free, no ads, no tracking.';
  if (desc.length > 160) desc = 'The words of ' + en + ' in Irish and English, side by side, with a gentle sing-along tune. Free, no ads.';
  return { title: title, desc: desc };
}

function page(entry, all) {
  var s = byId[entry.id], t = titles(s), url = BASE + 'singalong/' + s.id + '/';
  var img = SA.pick(s.image, 'en'), alt = SA.pick(s.alt, 'en');
  var block = function (lang) {
    return verses(s, lang).map(function (v) {
      return '      <p>' + v.map(esc).join('<br>\n        ') + '</p>';
    }).join('\n');
  };
  var others = all.filter(function (p) { return p.id !== s.id; }).map(function (p) {
    return '<a href="../' + esc(p.id) + '/">' + esc(byId[p.id].title.en) + '</a>';
  });
  var checked = entry.checked
    ? ' A fluent Irish speaker checked them' + (entry.checkedBy ? ' (' + esc(entry.checkedBy) + ')' : '') + '.'
    : '';
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">',
    MARK,
    '<title>' + esc(t.title) + ' · Calm Match</title>',
    '<meta name="description" content="' + esc(t.desc) + '">',
    '<link rel="canonical" href="' + url + '">',
    entry.preview ? '<meta name="robots" content="noindex">' : null,
    '<meta property="og:title" content="' + esc(t.title) + ' · Calm Match">',
    '<meta property="og:description" content="' + esc(t.desc) + '">',
    '<meta property="og:type" content="website">',
    '<meta property="og:url" content="' + url + '">',
    '<meta property="og:site_name" content="Calm Match">',
    '<meta property="og:locale" content="en_IE">',
    '<meta property="og:locale:alternate" content="ga_IE">',
    '<meta property="og:image" content="' + BASE + 'icons/share.png">',
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta property="og:image:alt" content="Calm Match: calm learning games in English and Irish, for neurodivergent children. Free.">',
    '<meta name="twitter:card" content="summary_large_image">',
    '<meta name="theme-color" content="#3f7c74">',
    '<link rel="manifest" href="../../manifest.webmanifest">',
    '<link rel="icon" href="../../icons/icon.svg" type="image/svg+xml">',
    '<link rel="apple-touch-icon" href="../../icons/apple-touch-icon.png">',
    '<link rel="stylesheet" href="../../css/base.css">',
    '<style>',
    '  .song-pic { display: block; width: 100%; max-width: 400px; height: auto; border-radius: 18px; border: 2px solid var(--line); margin: 18px 0; }',
    '  .song-go { display: flex; flex-wrap: wrap; gap: 12px; margin: 8px 0 8px; }',
    '  .song-go a { display: inline-flex; align-items: center; min-height: 48px; padding: 0 20px; border-radius: 14px; font-weight: 700; text-decoration: none; border: 2px solid var(--accent); color: var(--accent); background: var(--surface); }',
    '  .song-go a.main { background: var(--accent); color: var(--accent-ink); }',
    '  .words { display: grid; gap: 8px 40px; grid-template-columns: 1fr; }',
    '  @media (min-width: 720px) { .words { grid-template-columns: 1fr 1fr; } }',
    '  .words p { margin: 0 0 18px; font-size: 19px; line-height: 1.6; }',
    '  .note { color: var(--muted); font-size: 16px; }',
    '</style>',
    '</head>',
    '<body>',
    '<a class="skip" href="#main">Skip to content</a>',
    '<header class="site-head">',
    '  <a class="brand" href="../../index.html"><i></i>Calm Match</a>',
    '  <nav class="site-nav" aria-label="Main">',
    '    <a href="../../index.html">About</a><a href="../">Sing along</a><a href="../../alphabet/">Alphabet</a><a href="../../support.html">Support</a><a class="cta" href="../../play.html">Play</a>',
    '  </nav>',
    '</header>',
    '<main id="main" class="page"><article class="prose">',
    '  <h1>' + esc(s.title.en) + ' in Irish and English</h1>',
    '  <p class="lede">In Irish it is <i lang="ga">' + esc(s.title.ga) + '</i>. Here are the words in both languages, side by side, with a gentle tune to sing along to.</p>',
    '  <img class="song-pic" src="../images/' + esc(img) + '" alt="' + esc(alt) + '" width="400" height="300">',
    '  <div class="song-go">',
    '    <a class="main" href="../player.html?song=' + esc(s.id) + '&amp;lang=ga">Sing along in Irish</a>',
    '    <a href="../player.html?song=' + esc(s.id) + '&amp;lang=en">Sing along in English</a>',
    '  </div>',
    '  <p class="note">The words light up as the tune plays. No microphone, nothing to sign up for.</p>',
    '  <div class="words">',
    '    <section lang="ga" aria-labelledby="h-ga">',
    '      <h2 id="h-ga">' + esc(s.title.ga) + ' <span lang="en">(Irish)</span></h2>',
    block('ga'),
    '    </section>',
    '    <section aria-labelledby="h-en">',
    '      <h2 id="h-en">' + esc(s.title.en) + ' (English)</h2>',
    block('en'),
    '    </section>',
    '  </div>',
    '  <h2>About the song</h2>',
    '  <p>' + esc(s.source) + '</p>',
    '  <p>The Irish words were written for Calm Match to fit the same tune, one syllable to each note.' + checked + ' Spotted something to improve? Email <a href="mailto:hello@calmmatch.com">hello@calmmatch.com</a>.</p>',
    others.length ? '  <h2>More songs in Irish and English</h2>\n  <p>' + others.join(' · ') + '</p>' : null,
    '  <p><a href="../">All the sing-along songs</a></p>',
    '</article></main>',
    '<footer class="site-foot">',
    '  <span>© J.P Cunningham</span>',
    '  <nav aria-label="Legal"><a href="../../privacy.html">Privacy</a><a href="../../privacy-kids.html">Privacy for children</a><a href="../../cookies.html">Cookies</a><a href="../../terms.html">Terms</a><a href="../../accessibility.html">Accessibility</a><a href="../../support.html">Support the site</a><a href="../../credits.html">Credits</a></nav>',
    '</footer>',
    '</body>',
    '</html>',
    ''
  ].filter(function (l) { return l !== null; }).join('\n');
}

// ---- what the files should be ----
var want = {};   // relative path → content
published.forEach(function (p) { want['singalong/' + p.id + '/index.html'] = page(p, published); });

function replaceBlock(text, start, end, inner, file) {
  var a = text.indexOf(start), b = text.indexOf(end);
  if (a < 0 || b < a) { console.error(file + ': markers ' + start + ' … ' + end + ' not found'); process.exit(1); }
  return text.slice(0, a + start.length) + inner + text.slice(b);
}
var smPath = path.join(SITE, 'sitemap.xml');
var sm = fs.readFileSync(smPath, 'utf8');
var live = published.filter(function (p) { return !p.preview; });
var smWant = replaceBlock(sm, '<!-- song pages: made by tools/song-pages.js -->', '<!-- /song pages -->',
  '\n' + live.map(function (p) { return '  <url><loc>' + BASE + 'singalong/' + p.id + '/</loc></url>\n'; }).join('') + '  ', 'sitemap.xml');
var saPath = path.join(DIR, 'index.html');
var sa = fs.readFileSync(saPath, 'utf8');
var saWant = replaceBlock(sa, '<!-- song pages: made by tools/song-pages.js -->', '<!-- /song pages -->',
  live.length ? '\n  <p class="about-note song-words">Words in Irish and English: ' + live.map(function (p) {
    return '<a href="' + p.id + '/">' + esc(byId[p.id].title.en) + '</a>';
  }).join(' · ') + '</p>\n  ' : '', 'singalong/index.html');

// Pages made by this tool that should no longer be there.
var stale = fs.readdirSync(DIR).filter(function (d) {
  var f = path.join(DIR, d, 'index.html');
  return fs.existsSync(f) && fs.readFileSync(f, 'utf8').indexOf(MARK) > -1 && !want['singalong/' + d + '/index.html'];
});

if (CHECK) {
  var out = [];
  Object.keys(want).forEach(function (rel) {
    var f = path.join(SITE, rel);
    if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== want[rel]) out.push(rel + ' is out of date');
  });
  if (sm !== smWant) out.push('sitemap.xml song list is out of date');
  if (sa !== saWant) out.push('singalong/index.html song list is out of date');
  stale.forEach(function (d) { out.push('singalong/' + d + '/ is no longer listed'); });
  if (out.length) { console.log(out.join('\n') + '\nRun: node tools/song-pages.js'); process.exit(1); }
  console.log('Song pages up to date: ' + live.length + ' published.');
  process.exit(0);
}

Object.keys(want).forEach(function (rel) {
  var f = path.join(SITE, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, want[rel]);
});
stale.forEach(function (d) { fs.rmSync(path.join(DIR, d), { recursive: true }); });
fs.writeFileSync(smPath, smWant);
fs.writeFileSync(saPath, saWant);
console.log('Song pages: ' + live.length + ' published' + (PREVIEW ? ', preview of ' + PREVIEW : '') +
  (stale.length ? '; removed ' + stale.join(', ') : '') + '.');
